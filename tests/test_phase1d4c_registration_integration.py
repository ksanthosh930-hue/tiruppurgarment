    def test_05_end_to_end_persistence_execution(self):
        """Simulate backend database persistence with frontend attribution payload"""
        executed = []

        def mock_exec(sql, params):
            executed.append({"sql": sql, "params": params})
            return 1

        payload_obj = MarketingAttributionPayload(**self.sample_frontend_payload)

        success = persist_user_marketing_attribution(
            exec_fn=mock_exec,
            user_id=777,
            account_type="company",
            attribution_payload=payload_obj,
            raw_metadata={"registration_flow": "register_complete"}
        )

        self.assertTrue(success)
        self.assertEqual(len(executed), 1)
        params = executed[0]["params"]

        # Check bound parameters
        self.assertEqual(params[0], 777)                             # user_id
        self.assertEqual(params[1], "company")                         # account_type
        self.assertEqual(params[2], "instagram")                       # first_utm_source
        self.assertEqual(params[3], "paid_social")                     # first_utm_medium
        self.assertEqual(params[4], "garment_workers_nov")             # first_utm_campaign
        self.assertEqual(params[10], "google")                         # last_utm_source
        self.assertEqual(params[11], "cpc")                            # last_utm_medium
        self.assertEqual(params[12], "search_hiring_jobs")             # last_utm_campaign
        self.assertEqual(params[18], "v_test_frontend_user_001")       # visitor_id

        meta = json.loads(params[19])
        self.assertTrue(meta["attribution_supplied"])
        self.assertFalse(meta["server_fallback"])
        self.assertEqual(meta["classified_first_channel"], "instagram")
        self.assertEqual(meta["classified_last_channel"], "google")

