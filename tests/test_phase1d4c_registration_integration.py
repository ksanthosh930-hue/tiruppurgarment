    def test_09_candidate_quick_registration_persistence_failure_resilience(self):
        """REV-01: Database persistence failure in attribution must never disrupt registration"""
        def mock_broken_exec(sql, params):
            raise RuntimeError("Database connection timed out")

        new_pub_user_id = 891
        parsed_attr_payload = MarketingAttributionPayload(**self.sample_frontend_payload)

        # Simulation of the try/except block in routers/jobs.py
        try:
            persist_user_marketing_attribution(
                exec_fn=mock_broken_exec,
                user_id=new_pub_user_id,
                account_type="individual",
                attribution_payload=parsed_attr_payload
            )
        except Exception as e:
            self.fail("Attribution persistence should handle db exceptions internally without re-raising")

