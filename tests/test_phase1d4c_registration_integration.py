class TestFrontendRegistrationIntegration(unittest.TestCase):
    """End-to-end integration tests between frontend payload structure and registration models"""

    def setUp(self):
        # Canonical payload emitted by getMarketingAttributionPayload()
        self.sample_frontend_payload = {
            "visitor_id": "v_test_frontend_user_001",
            "first_touch": {
                "source": "instagram",
                "medium": "paid_social",
                "campaign": "garment_workers_nov",
                "content": "video_ad_reel",
                "term": "tailors tirupur",
                "landing_page": "https://tirupurgarment.in/?utm_source=instagram&utm_medium=paid_social&utm_campaign=garment_workers_nov",
                "referrer": "https://l.instagram.com/",
                "visit_at": "2026-11-20T10:00:00.000Z"
            },
            "last_touch": {
                "source": "google",
                "medium": "cpc",
                "campaign": "search_hiring_jobs",
                "content": None,
                "term": "job vacancy tirupur",
                "landing_page": "https://tirupurgarment.in/signup?gclid=12345",
                "referrer": "https://www.google.co.in/",
                "visit_at": "2026-11-25T11:00:00.000Z"
            },
            "raw_metadata": {
                "client_captured": True,
                "viewport": "1280x720",
                "tz": "Asia/Kolkata"
            }
        }

    def test_01_complete_registration_model_parsing(self):
        """Step 3 of standard email/OTP signup via /api/auth/register/complete"""
        data = {
            "email": "seeker@example.com",
            "account_type": "individual",
            "password": "SecurePassword123!",
            "confirm_password": "SecurePassword123!",
            "full_name": "Kavitha Raman",
            "mobile": "9842101234",
            "location": "Tirupur",
            "visitor_id": self.sample_frontend_payload["visitor_id"],
            "attribution": self.sample_frontend_payload
        }

        req = CompleteRegistrationRequest(**data)
        self.assertIsNotNone(req.attribution)
        self.assertEqual(req.attribution.visitor_id, "v_test_frontend_user_001")
        self.assertEqual(req.attribution.first_touch.source, "instagram")
        self.assertEqual(req.attribution.first_touch.medium, "paid_social")
        self.assertEqual(req.attribution.last_touch.source, "google")
        self.assertEqual(req.attribution.last_touch.medium, "cpc")

